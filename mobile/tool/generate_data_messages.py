#!/usr/bin/env python3
"""Generate the repository's pure-Dart message subset from the app ARB bundles.

Keeps HTTP/domain adapters usable by Dart CLI checks without importing dart:ui.
Run after editing ARB messages used by the repositories or demo fixtures.
"""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
files = [root / 'lib/data/seatmap_repository.dart', root / 'lib/data/demo_data.dart']
keys = sorted(set(re.findall(r'appStrings\.(\w+)', '\n'.join(p.read_text() for p in files))))
bundles = {lang: json.loads((root / f'lib/l10n/app_{lang}.arb').read_text()) for lang in ['ru', 'bg', 'en']}
output = ["// Generated by tool/generate_data_messages.py from the ARB bundles.", "import 'language_state.dart';", "export 'language_state.dart';", "DataMessages get appStrings => DataMessages(AppLanguage.code);", "class DataMessages {", "  const DataMessages(this.language);", "  final String language;"]
for key in keys:
    params = list(bundles['ru'].get('@'+key, {}).get('placeholders', {}))
    values = {lang: bundle[key] for lang, bundle in bundles.items()}
    signature = '(' + ', '.join('String '+p for p in params) + ')' if params else ''
    output.append(f"  String {'get ' if not params else ''}{key}{signature} {{")
    output.append('    final value = switch (language) {')
    for lang in ['bg', 'en']:
        value = json.dumps(values[lang], ensure_ascii=False).replace('$', '\\$')
        output.append(f"      '{lang}' => {value},")
    value = json.dumps(values['ru'], ensure_ascii=False).replace('$', '\\$')
    output.append(f"      _ => {value},\n    }};")
    suffix = ''.join(f".replaceAll('{{{p}}}', {p})" for p in params)
    output.append(f'    return value{suffix};\n  }}')
output.append('}')
(root / 'lib/l10n/data_messages.dart').write_text('\n'.join(output)+'\n')
print(f'Generated {len(keys)} repository messages from the ARB bundles.')
